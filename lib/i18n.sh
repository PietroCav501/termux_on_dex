TOD_LANG=${TOD_LANG:-it}

i18n_init() {
  local l
  l=$(conf_get UI_LANG)
  # la lingua scelta per il desktop vale anche per tod (getprop non va sotto proot)
  if [[ -z $l ]]; then l=$(conf_get LINGUA); fi
  if [[ -z $l ]]; then l=$(getprop persist.sys.locale 2>/dev/null || true); fi
  if [[ -z $l ]]; then l=$(getprop ro.product.locale 2>/dev/null || true); fi
  if [[ -z $l ]]; then l=${LANG:-en}; fi
  case ${l,,} in it*) TOD_LANG=it ;; *) TOD_LANG=en ;; esac
}

t() { # t chiave [argomenti...]
  local key=$1 s
  shift
  if [[ $TOD_LANG == it ]]; then s=${TOD_MSG_it[$key]-}; else s=${TOD_MSG_en[$key]-}; fi
  if [[ -z $s ]]; then s=${TOD_MSG_en[$key]-$key}; fi
  # shellcheck disable=SC2059
  printf -- "$s" "$@"
}

