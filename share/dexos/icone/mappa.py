def base(nome):
    for s in ("-symbolic", "-rtl", "-ltr", "-dark", "-light"):
        if nome.endswith(s):
            nome = nome[: -len(s)]
    return nome


def glifo(nome, contesto=None):
    """il simbolo per un nome (None se nessuna regola: il chiamante usa RIPIEGO)"""
    b = base(nome)
    if b.endswith("-rtl") or b.endswith("-ltr"):
        b = b[:-4]
    for e, g in _REGOLE:
        m = e.search(b)
        if m:
            return m.expand(g) if "\\" in g else g
    return None
